export class I18n {
  constructor(initial) {
    const saved = localStorage.getItem("pandaslab-lang");
    const guess = (navigator.language || "zh").toLowerCase().startsWith("zh") ? "zh" : "en";
    this.lang = initial || saved || guess;
    this.listeners = [];
  }
  get d() { return DICT[this.lang]; }
  t(key, ...args) {
    const v = this.d[key];
    if (v === undefined) return key;
    return typeof v === "function" ? v(...args) : v;
  }
  isEn() { return this.lang === "en"; }
  toggle() {
    this.lang = this.lang === "en" ? "zh" : "en";
    localStorage.setItem("pandaslab-lang", this.lang);
    this.apply();
    this.listeners.forEach((f) => f(this.lang));
  }
  onChange(fn) { this.listeners.push(fn); }

  /** 把 data-i18n 标记的静态文案刷一遍 */
  apply() {
    document.documentElement.lang = this.isEn() ? "en" : "zh-CN";
    document.title = this.t("docTitle");
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const v = this.d[el.dataset.i18n];
      if (typeof v === "string") el.textContent = v;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      const v = this.d[el.dataset.i18nPlaceholder];
      if (typeof v === "string") el.setAttribute("placeholder", v);
    });
  }
}
